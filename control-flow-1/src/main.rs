fn main() {
    let my_age = 58;
    if my_age == 30 {
        println!("My age is 30");
    } else if my_age != 59 {
        println!("My age is not 59");
    } else if my_age < 30 {
        println!("My age is less than 30");
    } else {
        println!("My age is greater than 30");
    }

    let running: bool = true;
    if running {
        println!("I am running");
    } else {
        println!("I am not running");
    }
}
